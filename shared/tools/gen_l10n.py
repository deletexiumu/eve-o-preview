"""界面文案的校验与代码生成（docs/windows/architecture.md 5.2 节）。只用 Python 3.11+ 的标准库。

数据在 shared/l10n/：
- keys/<域>.toml：域的说明（notes）；每个协议（[protocols.<协议>]）的说明与 L10n 上的访问器名（accessor）；
  每条文案（[<协议>.<键>]）的说明、参数、所在分节。按数量变化的文案写 plural = "<参数>"，
  按参数取值分支的写 select = "<参数>" 与 cases。
- <语言>/<域>.toml：每种语言一份，[<协议>] 下每个键一条文字。

生成的 Swift（macos/Sources/EVEOPreview/Localization/Generated/）：
- <域的 swift_file>.swift：协议与 L10n 上的访问器。
- <语言>/<域的 swift_file>+<语言>.swift：每种语言每个协议一个结构体，类型名是「协议名 + 大写语言代码」。
- L10nPlural.swift：复数规则。

文字里的占位符：
- {名字}：参数原样插入。
- {名字:格式}：secs（整数不带小数点，其余一位小数）、secs_comma（同上，小数点写逗号）、
  .0f / .1f（定点小数）、.1f_locale（按该语言的习惯写一位小数）、list（用「, 」连接）、
  list_cjk（每项加「」，用「、」连接）。
- {{ 与 }}：字面的花括号。
复数：值写成表，键是该语言的复数类别（见 PLURAL_CATEGORIES）；所有数量用同一句话时可以直接写字符串。
分支：值写成表，键是 cases 里的每一项。参数是字符串时为 empty / other，可选值时为 none / some。

校验不通过时列出全部问题，退出码为 1。

用法：
  python3 shared/tools/gen_l10n.py              校验并重新生成全部代码
  python3 shared/tools/gen_l10n.py --check      只校验，并核对已提交的生成结果没有过期
"""

from __future__ import annotations

import argparse
import re
import sys
import tomllib
from dataclasses import dataclass, field
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
L10N = ROOT / "shared/l10n"
SWIFT_OUT = ROOT / "macos/Sources/EVEOPreview/Localization/Generated"

# 语言的顺序与 macOS 的 AppLanguage 一致。
LANGS = ["en", "zh", "ru", "ja", "ko", "fr", "de", "es"]

# 每种语言用到的复数类别（只考虑非负整数）。最后一项是兜底。
PLURAL_CATEGORIES = {
    "en": ["one", "other"],
    "de": ["one", "other"],
    "es": ["one", "other"],
    "fr": ["one", "other"],
    "ru": ["one", "few", "many"],
    "zh": ["other"],
    "ja": ["other"],
    "ko": ["other"],
}

# 占位符的格式，以及每种格式适用的参数类型。
FORMATS = {
    None: {"String", "Int", "Int32", "Int64"},
    "secs": {"Double"},
    "secs_comma": {"Double"},
    ".0f": {"Double"},
    ".1f": {"Double"},
    ".1f_locale": {"Double"},
    "list": {"[String]"},
    "list_cjk": {"[String]"},
}

PLACEHOLDER = re.compile(r"\{\{|\}\}|\{([A-Za-z_]\w*)(?::([^{}]+))?\}|[{}]")

# 生成文件开头的标记：质量门禁据此跳过（scripts/check_quality.py）。
GENERATED = "@generated by shared/tools/gen_l10n.py — 不要手改，改 shared/l10n/ 里的 TOML 后重新生成。"


@dataclass
class Param:
    """一个参数：Swift 的外部标签、内部名与类型。"""

    label: str
    name: str
    type: str

    @property
    def swift(self) -> str:
        if self.label == self.name:
            return f"{self.name}: {self.type}"
        return f"{self.label} {self.name}: {self.type}"


@dataclass
class Key:
    """一条文案的定义。"""

    proto: str
    name: str
    doc: str
    section: str | None
    params: list[Param]
    plural: str | None = None
    select: str | None = None
    cases: list[str] = field(default_factory=list)

    @property
    def is_func(self) -> bool:
        return bool(self.params)

    def param(self, name: str) -> Param | None:
        return next((p for p in self.params if p.name == name), None)


@dataclass
class Protocol:
    """一个协议：说明与 L10n 上的访问器名。"""

    doc: str
    accessor: str


@dataclass
class Domain:
    """一个域：一个 keys 文件，对应 macOS 的一组 Swift 文件。"""

    name: str
    swift_file: str
    notes: str
    protocols: dict[str, Protocol]
    keys: list[Key]
    texts: dict[str, dict[str, dict[str, object]]] = field(default_factory=dict)


def parse_param(text: str) -> Param:
    """「_ path: String」「directory: String」→ Param。"""
    head, typ = text.split(":", 1)
    words = head.split()
    label, name = (words[0], words[1]) if len(words) == 2 else (words[0], words[0])
    return Param(label, name, typ.strip())


def load() -> list[Domain]:
    """读全部 TOML。"""
    domains = []
    for path in sorted((L10N / "keys").glob("*.toml")):
        data = tomllib.loads(path.read_text(encoding="utf-8"))
        protocols = {name: Protocol(info["doc"].strip(), info["accessor"])
                     for name, info in data.pop("protocols").items()}
        swift_file = data.pop("swift_file")
        notes = data.pop("notes").strip()
        keys = []
        for proto in protocols:
            for name, info in data.get(proto, {}).items():
                keys.append(Key(proto, name, info.get("doc", ""), info.get("section"),
                                [parse_param(p) for p in info.get("params", [])],
                                info.get("plural"), info.get("select"), info.get("cases", [])))
        domain = Domain(path.stem, swift_file, notes, protocols, keys)
        for lang in LANGS:
            lang_path = L10N / lang / path.name
            domain.texts[lang] = tomllib.loads(lang_path.read_text(encoding="utf-8")) if lang_path.exists() else {}
        domains.append(domain)
    return domains


def placeholders(template: str) -> list[tuple[str, str | None]] | str:
    """模板里的占位符；格式不对时返回错误说明。"""
    found = []
    for m in PLACEHOLDER.finditer(template):
        token = m.group(0)
        if token in ("{{", "}}"):
            continue
        if m.group(1) is None:
            return f"单独的花括号（字面的花括号写成 {{{{ 或 }}}}）：{template!r}"
        found.append((m.group(1), m.group(2)))
    return found


def select_cases(key: Key) -> list[str]:
    """分支的全部取值。"""
    param = key.param(key.select)
    if param.type == "String":
        return ["empty", "other"]
    if param.type.endswith("?"):
        return ["none", "some"]
    return key.cases


def variants(key: Key, lang: str, value: object) -> dict[str, str] | str:
    """一条文字的各个变体（复数类别或分支）；结构不对时返回错误说明。"""
    if isinstance(value, str):
        if key.select:
            return "分支文案要写成表"
        return {"": value}
    if not isinstance(value, dict) or not all(isinstance(v, str) for v in value.values()):
        return "值必须是字符串或字符串的表"
    if key.plural:
        expected = PLURAL_CATEGORIES[lang]
    elif key.select:
        expected = select_cases(key)
    else:
        return "只有 plural 或 select 的文案能写成表"
    if list(value) != expected:
        return f"表的键应为 {expected}，实际是 {list(value)}"
    return value


def validate(domains: list[Domain]) -> list[str]:
    """校验全部文案，返回问题列表。"""
    problems = []
    for domain in domains:
        for key in domain.keys:
            where = f"{domain.name}: {key.proto}.{key.name}"
            for attr in ("plural", "select"):
                ref = getattr(key, attr)
                if ref and not key.param(ref):
                    problems.append(f"{where}: {attr} 指向不存在的参数 {ref}")
            if key.plural and key.param(key.plural) and key.param(key.plural).type != "Int":
                problems.append(f"{where}: plural 的参数必须是 Int")
            if key.select and key.param(key.select):
                typ = key.param(key.select).type
                if typ not in ("String",) and not typ.endswith("?") and not key.cases:
                    problems.append(f"{where}: 枚举分支要写 cases")
        for lang in LANGS:
            texts = domain.texts[lang]
            for proto in domain.protocols:
                section = texts.get(proto, {})
                expected = {k.name for k in domain.keys if k.proto == proto}
                for extra in sorted(set(section) - expected):
                    problems.append(f"{lang}/{domain.name}: {proto}.{extra} 不在 keys 里")
            for extra in sorted(set(texts) - set(domain.protocols)):
                problems.append(f"{lang}/{domain.name}: 多余的表 [{extra}]")
            for key in domain.keys:
                where = f"{lang}/{domain.name}: {key.proto}.{key.name}"
                value = texts.get(key.proto, {}).get(key.name)
                if value is None:
                    problems.append(f"{where}: 缺少")
                    continue
                result = variants(key, lang, value)
                if isinstance(result, str):
                    problems.append(f"{where}: {result}")
                    continue
                for case, template in result.items():
                    found = placeholders(template)
                    if isinstance(found, str):
                        problems.append(f"{where}: {found}")
                        continue
                    for name, fmt in found:
                        param = key.param(name)
                        if not param:
                            problems.append(f"{where}: 占位符 {{{name}}} 不是参数")
                            continue
                        typ = param.type
                        # 可选值的分支里，some 分支按解包后的类型算。
                        if key.select == name and typ.endswith("?"):
                            if case != "some":
                                problems.append(f"{where}: {{{name}}} 只能出现在 some 分支")
                                continue
                            typ = typ[:-1]
                        if fmt not in FORMATS:
                            problems.append(f"{where}: 不认识的格式 {fmt}")
                        elif typ not in FORMATS[fmt]:
                            problems.append(f"{where}: 格式 {fmt} 不适用于 {typ} 类型的 {name}")
    return problems


# ---------------------------------------------------------------- Swift

def swift_string(template: str, key: Key, lang: str) -> str:
    """模板 → Swift 字符串字面量（含插值）。"""
    out = []
    pos = 0
    for m in PLACEHOLDER.finditer(template):
        out.append(swift_escape(template[pos:m.start()]))
        pos = m.end()
        token = m.group(0)
        if token in ("{{", "}}"):
            out.append(token[0])
            continue
        name, fmt = m.group(1), m.group(2)
        out.append("\\(" + swift_format(name, fmt, lang) + ")")
    out.append(swift_escape(template[pos:]))
    return '"' + "".join(out) + '"'


def swift_escape(text: str) -> str:
    return text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\t", "\\t")


def swift_format(name: str, fmt: str | None, lang: str) -> str:
    """占位符 → Swift 表达式。"""
    if fmt is None:
        return name
    if fmt == "secs":
        return f"combatSecondsNumber({name})"
    if fmt == "secs_comma":
        return f'combatSecondsNumber({name}).replacingOccurrences(of: ".", with: ",")'
    if fmt in (".0f", ".1f"):
        return f'String(format: "%{fmt}", {name})'
    if fmt == ".1f_locale":
        return f'{name}.formatted(.number.precision(.fractionLength(1)).locale(Locale(identifier: "{lang}")))'
    if fmt == "list":
        return f'{name}.joined(separator: ", ")'
    if fmt == "list_cjk":
        return f'{name}.map {{ "「\\($0)」" }}.joined(separator: "、")'
    raise ValueError(fmt)


def swift_member(key: Key, lang: str, value: object, indent: str) -> list[str]:
    """一条文案的 Swift 实现。"""
    vs = variants(key, lang, value)
    if not key.is_func:
        return [f"{indent}var {key.name}: String {{ {swift_string(vs[''], key, lang)} }}"]
    sig = f"{indent}func {key.name}({', '.join(p.swift for p in key.params)}) -> String"
    if "" in vs:
        return [f"{sig} {{ {swift_string(vs[''], key, lang)} }}"]
    body = []
    inner = indent + "    "
    if key.plural:
        cats = list(vs)
        if len(cats) == 1:
            return [f"{sig} {{ {swift_string(vs[cats[0]], key, lang)} }}"]
        body.append(f"{inner}switch L10nPlural.{lang}({key.plural}) {{")
        for cat in cats[:-1]:
            body.append(f"{inner}case .{cat}: return {swift_string(vs[cat], key, lang)}")
        body.append(f"{inner}default: return {swift_string(vs[cats[-1]], key, lang)}")
        body.append(f"{inner}}}")
    else:
        param = key.param(key.select)
        if param.type == "String":
            body.append(f"{inner}{param.name}.isEmpty")
            body.append(f"{inner}    ? {swift_string(vs['empty'], key, lang)}")
            body.append(f"{inner}    : {swift_string(vs['other'], key, lang)}")
        elif param.type.endswith("?"):
            body.append(f"{inner}if let {param.name} {{ return {swift_string(vs['some'], key, lang)} }}")
            body.append(f"{inner}return {swift_string(vs['none'], key, lang)}")
        else:
            body.append(f"{inner}switch {param.name} {{")
            for case in key.cases:
                body.append(f"{inner}case .{case}: return {swift_string(vs[case], key, lang)}")
            body.append(f"{inner}}}")
    return [f"{sig} {{", *body, f"{indent}}}"]


def swift_doc(text: str, indent: str = "") -> list[str]:
    """说明文字 → 每行一条 /// 注释。"""
    return [f"{indent}/// {line}".rstrip() for line in text.splitlines()]


def swift_lang_file(domain: Domain, lang: str) -> str:
    """一个域一种语言的 Swift 文件。"""
    lines = [f"// {GENERATED}", "//", f"// {domain.name} 域的文字（{lang}），来自 shared/l10n/{lang}/{domain.name}.toml。", "",
             "import Foundation", "import EVEOPreviewCore", ""]
    for proto, info in domain.protocols.items():
        lines.append(f"/// {info.doc.splitlines()[0].rstrip('。')}（{lang}）。")
        lines.append(f"struct {proto}{lang.upper()}: {proto} {{")
        for key in (k for k in domain.keys if k.proto == proto):
            if key.section:
                lines.append(f"    // MARK: {key.section}")
            lines.extend(swift_member(key, lang, domain.texts[lang][proto][key.name], "    "))
        lines.append("}")
        lines.append("")
    return "\n".join(lines)


def swift_protocol_file(domain: Domain) -> str:
    """一个域的协议与 L10n 上的访问器。"""
    lines = [f"// {GENERATED}", "//"]
    lines += [f"// {line}".rstrip() for line in domain.notes.splitlines()]
    lines += ["//",
              "// 每种语言对每个协议各有一个不含存储属性的结构体（<语言>/ 下的文件）。带参数的文字是函数。",
              "// 访问器按 L10n.language 每次访问时取，切换语言后下次访问即是新语言；switch 不写 default，",
              "// 加语言时编译器会指出要补的地方。",
              "", "import Foundation", "import EVEOPreviewCore", ""]
    for proto, info in domain.protocols.items():
        lines += swift_doc(info.doc)
        lines.append(f"protocol {proto}: Sendable {{")
        first = True
        for key in (k for k in domain.keys if k.proto == proto):
            if key.section:
                if not first:
                    lines.append("")
                lines.append(f"    // MARK: {key.section}")
            first = False
            lines += swift_doc(key.doc, "    ")
            if key.is_func:
                lines.append(f"    func {key.name}({', '.join(p.swift for p in key.params)}) -> String")
            else:
                lines.append(f"    var {key.name}: String {{ get }}")
        lines.append("}")
        lines.append("")
    lines.append("extension L10n {")
    for i, (proto, info) in enumerate(domain.protocols.items()):
        if i:
            lines.append("")
        lines.append(f"    /// {info.doc.splitlines()[0]}")
        lines.append(f"    static var {info.accessor}: any {proto} {{")
        lines.append("        switch L10n.language {")
        for lang in LANGS:
            lines.append(f"        case .{lang}: return {proto}{lang.upper()}()")
        lines.append("        }")
        lines.append("    }")
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


SWIFT_SUPPORT = f"""// {GENERATED}
//
// 生成的文案用到的复数规则。只考虑非负整数；规则与原先各语言手写的判断一致。

/// 复数类别。
enum L10nPluralCategory {{
    case one, few, many, other
}}

/// 各语言的复数规则。
enum L10nPlural {{
    /// 英文、德文、西班牙文：1 为单数。
    static func en(_ n: Int) -> L10nPluralCategory {{ abs(n) == 1 ? .one : .other }}
    static func de(_ n: Int) -> L10nPluralCategory {{ en(n) }}
    static func es(_ n: Int) -> L10nPluralCategory {{ en(n) }}
    /// 法文：0 与 1 为单数。
    static func fr(_ n: Int) -> L10nPluralCategory {{ abs(n) < 2 ? .one : .other }}
    /// 俄文：个位 1（11 除外）为 one；个位 2～4（12～14 除外）为 few；其余为 many。
    static func ru(_ n: Int) -> L10nPluralCategory {{
        let lastTwo = abs(n) % 100
        let last = abs(n) % 10
        if (11...14).contains(lastTwo) {{ return .many }}
        if last == 1 {{ return .one }}
        if (2...4).contains(last) {{ return .few }}
        return .many
    }}
}}
"""


# ---------------------------------------------------------------- 入口

def outputs(domains: list[Domain]) -> dict[Path, str]:
    """全部生成文件：路径 → 内容。"""
    files = {SWIFT_OUT / "L10nPlural.swift": SWIFT_SUPPORT}
    for domain in domains:
        files[SWIFT_OUT / f"{domain.swift_file}.swift"] = swift_protocol_file(domain)
        for lang in LANGS:
            files[SWIFT_OUT / lang / f"{domain.swift_file}+{lang}.swift"] = swift_lang_file(domain, lang)
    return files


def stale_files(files: dict[Path, str]) -> list[Path]:
    """内容过期的生成文件，以及生成目录里不该有的多余文件。"""
    stale = [p for p, text in files.items() if not p.exists() or p.read_text(encoding="utf-8") != text]
    extra = [p for p in SWIFT_OUT.rglob("*.swift") if p not in files]
    return stale + sorted(extra)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--check", action="store_true", help="只校验，并核对生成结果没有过期")
    args = parser.parse_args()

    domains = load()
    problems = validate(domains)
    if problems:
        print("\n".join(problems), file=sys.stderr)
        print(f"文案校验失败：{len(problems)} 个问题", file=sys.stderr)
        return 1
    files = outputs(domains)
    if args.check:
        stale = stale_files(files)
        if stale:
            print("生成结果过期，运行 python3 shared/tools/gen_l10n.py 后提交：", file=sys.stderr)
            print("\n".join(str(p.relative_to(ROOT)) for p in stale), file=sys.stderr)
            return 1
        print(f"文案校验通过，生成结果是最新的（{len(files)} 个文件）")
        return 0
    for path in SWIFT_OUT.rglob("*.swift"):
        if path not in files:
            path.unlink()
    for path, text in files.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
    count = sum(len(d.keys) for d in domains)
    print(f"文案校验通过：{count} 条 × {len(LANGS)} 种语言；生成 {len(files)} 个文件")
    return 0


if __name__ == "__main__":
    sys.exit(main())
